#!/usr/bin/env python3
"""Emit the local quotient and Schreier binding of one selected frame row.

Unlike the original row-28 pilot, this renderer accepts either possible
faithful binary-plane local image: the cyclic group of order three or the
full group of order six.  Lean reconstructs the local target as the literal
range of the stored stabilizer action on the three nonzero binary vectors.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile


SCHEMA = "frames8-selected-top-certificate-v1"
INPUT_LIMIT = 16 * 1024 * 1024
OUTPUT_LIMIT = 2 * 1024 * 1024
MODULE_RE = re.compile(r"[A-Z][A-Za-z0-9_]*\Z")


class Refused(ValueError):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise Refused(message)


def lean_array(values: list[int]) -> str:
    return "#[" + ",".join(map(str, values)) + "]"


def inverse_permutation(row: tuple[int, ...]) -> tuple[int, ...]:
    result = [0] * len(row)
    for i, x in enumerate(row):
        result[x - 1] = i + 1
    return tuple(result)


def read_input(path: Path) -> dict:
    require(path.is_file() and not path.is_symlink(), "missing prepared input")
    raw = path.read_bytes()
    require(len(raw) <= INPUT_LIMIT, "prepared input ceiling reached")
    data = json.loads(raw)
    require(isinstance(data, dict) and data.get("schema") == SCHEMA,
            "unexpected prepared schema")
    rows = [tuple(r) for r in data["cayley"]["rows"]]
    n = data["top_order"]
    generators = data["generators"]
    generator_count = len(generators)
    binding = data["binding"]
    induced = data["induced_binding"]
    require(len(rows) == n and n % 8 == 0 and 1 <= generator_count <= 16,
            "invalid top size")
    representative_rows_raw = [
        rows.index(inverse_permutation(tuple(r)))
        for r in binding["coset_representatives"]
    ]
    require(len(representative_rows_raw) == 8, "invalid coset representatives")
    representative_rows = list(reversed(representative_rows_raw))

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from prepare_frames8_selected_top_certificate import (
        Budget, paired_hom_enumeration, permutation_rows,
    )
    budget = Budget(2_000_000)
    stabilizer_generators = permutation_rows(
        binding["stabilizer_generators"], 8, budget)
    local_images = permutation_rows(binding["local_images"], 3, budget)
    hom = paired_hom_enumeration(stabilizer_generators, local_images, 8, 3, budget)
    zero_rows = [tuple(x - 1 for x in r) for r in rows]
    stabilizer_rows = []
    forward = [[0, 1, 2] for _ in range(n)]
    for row, image in zip(hom["rows"], hom["images"]):
        index = zero_rows.index(row)
        stabilizer_rows.append(index)
        forward[index] = list(image)
    stabilizer_rows.sort()
    require(len(stabilizer_rows) == n // 8, "wrong stabilizer size")
    inverse = []
    for row in forward:
        inv = [0, 0, 0]
        for i, q in enumerate(row):
            inv[q] = i
        inverse.append(inv)
    image_order = len(set(tuple(forward[i]) for i in stabilizer_rows))
    require(image_order in (3, 6), "local target is not order three or six")

    next_flat = []
    for row in induced["coset_next"]:
        coordinate_forward = [7 - row[7 - a] for a in range(8)]
        next_flat.extend(coordinate_forward.index(a) for a in range(8))
    require(len(next_flat) == generator_count * 8, "invalid Schreier next table")
    return {
        "source_row": data["source_row"],
        "top_order": n,
        "generator_count": generator_count,
        "stabilizer_rows": stabilizer_rows,
        "stabilizer_order": len(stabilizer_rows),
        "representative_rows": representative_rows,
        "local_forward": [q for row in forward for q in row],
        "local_inverse": [q for row in inverse for q in row],
        "local_order": image_order,
        "next": next_flat,
    }


def emit(module_name: str, representation_module: str, top_module: str,
         data: dict, input_name: str) -> str:
    n = data["top_order"]
    g = data["generator_count"]
    membership = " || ".join(f"i.val = {x}" for x in data["stabilizer_rows"])
    return f'''import SymmetricSubgroupAsymptotics.{representation_module}
import SymmetricSubgroupAsymptotics.PrimitiveAffineEightFrameLocalRowCatalogue
import SymmetricSubgroupAsymptotics.BinaryPlaneOrderThreeRepresentation

/-!
# Selected eight-frame row {data['source_row']}: local quotient and Schreier binding

Generated by `emit_lean_frames8_selected_induced_binding_general.py` from
`{input_name}`.  Lean checks the literal point stabilizer, its onto local
image of order {data['local_order']}, the eight right cosets, every Schreier
equation, and the sixteen-dimensional generator formula.
-/

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section

namespace SymmetricSubgroupAsymptotics.{module_name}

abbrev Source := {top_module}.Source
local instance sourceGroup : Group Source := {top_module}.group

def inStabilizer (i : Fin {n}) : Prop :=
  {membership}

local instance inStabilizerDecidable (i : Fin {n}) :
    Decidable (inStabilizer i) := by
  unfold inStabilizer
  infer_instance

private theorem one_inStabilizer :
    inStabilizer (1 : Source).index := by native_decide +revert

private theorem mul_inStabilizer : ∀ x y : Source,
    inStabilizer x.index → inStabilizer y.index →
      inStabilizer (x * y).index := by native_decide +revert

private theorem inv_inStabilizer : ∀ x : Source,
    inStabilizer x.index → inStabilizer x⁻¹.index := by native_decide +revert

def sourceStabilizer : Subgroup Source where
  carrier := {{x | inStabilizer x.index}}
  one_mem' := one_inStabilizer
  mul_mem' := by intro x y hx hy; exact mul_inStabilizer x y hx hy
  inv_mem' := by intro x hx; exact inv_inStabilizer x hx

local instance sourceStabilizerMembership (x : Source) :
    Decidable (x ∈ sourceStabilizer) :=
  inStabilizerDecidable x.index

theorem sourceStabilizer_card : Nat.card sourceStabilizer =
    {data['stabilizer_order']} := by
  rw [Nat.card_eq_fintype_card, Fintype.card_subtype]
  native_decide +revert

private def localForwardRow (i : Fin {n}) (q : Fin 3) : Fin 3 :=
  ({lean_array(data['local_forward'])} : Array (Fin 3))[3 * i.val + q.val]!

private def localInverseRow (i : Fin {n}) (q : Fin 3) : Fin 3 :=
  ({lean_array(data['local_inverse'])} : Array (Fin 3))[3 * i.val + q.val]!

private def localPermutation (i : Fin {n}) : Equiv.Perm (Fin 3) where
  toFun := localForwardRow i
  invFun := localInverseRow i
  left_inv := by native_decide +revert
  right_inv := by native_decide +revert

private theorem localPermutation_one :
    localPermutation (1 : Source).index = 1 := by native_decide +revert

private theorem localPermutation_mul : ∀ x y : sourceStabilizer,
    localPermutation (x * y).1.index =
      localPermutation x.1.index * localPermutation y.1.index := by
  native_decide +revert

def rawLocalMap : sourceStabilizer →* Equiv.Perm (Fin 3) where
  toFun x := localPermutation x.1.index
  map_one' := localPermutation_one
  map_mul' := localPermutation_mul

abbrev LocalTarget := MonoidHom.range rawLocalMap

def sourceLocalMap : sourceStabilizer →* LocalTarget :=
  rawLocalMap.rangeRestrict

theorem sourceLocalMap_surjective : Function.Surjective sourceLocalMap :=
  rawLocalMap.rangeRestrict_surjective

theorem localTarget_card : Nat.card LocalTarget = {data['local_order']} := by
  rw [Nat.card_eq_fintype_card]
  native_decide +revert

private def representativeRows (a : Fin 8) : Fin {n} :=
  ({lean_array(data['representative_rows'])} : Array (Fin {n}))[a.val]!

def representative (a : Fin 8) : Source := ⟨representativeRows a⟩

theorem representative_factor : ∀ x : Source,
    ∃ h : Source, h ∈ sourceStabilizer ∧
      ∃ a : Fin 8, x = h * representative a := by native_decide +revert

private def nextRows (j : Fin {g}) (a : Fin 8) : Fin 8 :=
  ({lean_array(data['next'])} : Array (Fin 8))[8 * j.val + a.val]!

def next (j : Fin {g}) (a : Fin 8) : Fin 8 := nextRows j a

def twist (j : Fin {g}) (a : Fin 8) : sourceStabilizer :=
  ⟨representative a * {top_module}.ambient j *
      (representative (next j a))⁻¹,
    by fin_cases j <;> fin_cases a <;> native_decide +revert⟩

theorem representative_mul_generator (j : Fin {g}) (a : Fin 8) :
    representative a * {top_module}.ambient j =
      (twist j a : Source) * representative (next j a) := by
  simp [twist]

private def localForwardColumns (z : LocalTarget) (i : Fin 2) : ℕ :=
  (z.1 (Fin.castSucc i)).val + 1

private def localInverseColumns (z : LocalTarget) (i : Fin 2) : ℕ :=
  ((z.1)⁻¹ (Fin.castSucc i)).val + 1

def localForwardMatrix (z : LocalTarget) :
    Matrix (Fin 2) (Fin 2) (ZMod 2) :=
  binaryMatrixOfColumnMasks 2 (localForwardColumns z)

def localInverseMatrix (z : LocalTarget) :
    Matrix (Fin 2) (Fin 2) (ZMod 2) :=
  binaryMatrixOfColumnMasks 2 (localInverseColumns z)

def localUnit (z : LocalTarget) :
    Units (Matrix (Fin 2) (Fin 2) (ZMod 2)) :=
  checkedMatrixUnit (localForwardMatrix z) (localInverseMatrix z)
    (by native_decide +revert) (by native_decide +revert)

private theorem localUnit_one : localUnit 1 = 1 := by native_decide

private theorem localUnit_mul : ∀ x y : LocalTarget,
    localUnit (x * y) = localUnit x * localUnit y := by native_decide

def localMatrixHom : LocalTarget →*
    Units (Matrix (Fin 2) (Fin 2) (ZMod 2)) where
  toFun := localUnit
  map_one' := localUnit_one
  map_mul' := localUnit_mul

def localRepresentation :
    Representation (ZMod 2) LocalTarget OrderThreeBinaryPlane :=
  matrixUnitRepresentation localMatrixHom

@[simp] theorem localRepresentation_apply
    (z : LocalTarget) (v : OrderThreeBinaryPlane) :
    localRepresentation z v = (localForwardMatrix z).mulVec v := rfl

theorem localMatrixHom_injective : Function.Injective localMatrixHom := by
  native_decide

theorem localRepresentation_injective :
    Function.Injective localRepresentation := by
  intro x y hxy
  apply localMatrixHom_injective
  apply Units.ext
  apply Matrix.ext
  intro i j
  have h := LinearMap.congr_fun hxy (Pi.single j 1)
  simpa [localRepresentation, matrixUnitRepresentation,
    Matrix.mulVec, Pi.single_apply] using congrFun h i

private theorem generatorFormula : ∀ (j : Fin {g})
    (v : {representation_module}.ModelModule)
    (a : Fin 8) (i : Fin 2),
    {representation_module}.representation ({top_module}.ambient j) v
        (CoinducedLeadingCoordinates.label a i) =
      localRepresentation (sourceLocalMap (twist j a))
        (fun q ↦ v (CoinducedLeadingCoordinates.label (next j a) q)) i := by
  native_decide

theorem representation_generator_formula (j : Fin {g})
    (v : {representation_module}.ModelModule)
    (a : Fin 8) (i : Fin 2) :
    {representation_module}.representation ({top_module}.ambient j) v
        (CoinducedLeadingCoordinates.label a i) =
      localRepresentation (sourceLocalMap (twist j a))
        (fun q ↦ v (CoinducedLeadingCoordinates.label (next j a) q)) i :=
  generatorFormula j v a i

end SymmetricSubgroupAsymptotics.{module_name}

end
'''


def write_atomic(path: Path, payload: bytes, force: bool) -> None:
    require(force or not path.exists(), "output exists; use --force")
    require(len(payload) <= OUTPUT_LIMIT, "Lean output byte ceiling reached")
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("wb", delete=False, dir=path.parent,
                                     prefix=path.name + ".",
                                     suffix=".partial") as stream:
        temporary = Path(stream.name)
        stream.write(payload)
    try:
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--module", required=True)
    parser.add_argument("--representation-module", required=True)
    parser.add_argument("--top-module", required=True)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    for name in (args.module, args.representation_module, args.top_module):
        require(MODULE_RE.fullmatch(name) is not None, "invalid Lean module")
    data = read_input(args.input)
    payload = emit(args.module, args.representation_module, args.top_module,
                   data, args.input.name).encode()
    write_atomic(args.output, payload, args.force)
    print(f"{args.output}: {len(payload)} bytes; local order {data['local_order']}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, KeyError, TypeError, json.JSONDecodeError, Refused) as error:
        raise SystemExit(f"refused: {error}")
