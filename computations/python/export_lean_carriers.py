assert label == '16T1086'
perm=list(range(16)); emb=chosen[0]
cycle=rawperm(header['base_alphabet'][e['word'][0]['base_index']-1]['generators'][0])
for x in range(4):perm[emb[x]]=emb[cycle[x]]
assert tuple(perm) not in {v[0]for v in ds['beta']['rows']}
s = '''import SymmetricSubgroupAsymptotics.BinaryExceptionalBlocks

/-!
# The proper degree-sixteen carrier correlation

The independent rotation of the literal C4 block is an element of the
full displayed block product, but is absent from the actual carrier.
Thus the reversible chart retains a proper subdirect core.
-/

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section

namespace SymmetricSubgroupAsymptotics.BinaryChart16T1086

'''
s += emit_perms('independentRotationPermutation',[tuple(perm)],16)
s += '''def independentRotation : Equiv.Perm (Fin 16) :=
  independentRotationPermutation 0

theorem independentRotation_on_cyclic_block : ∀ x,
    independentRotation (block0.embedding x) =
      block0.embedding (block0BaseGenerators 0 x) := by decide +kernel

'''
for i in range(1,4):
    s += f'''theorem independentRotation_on_block{i} : ∀ x,
    independentRotation (block{i}.embedding x) = block{i}.embedding x := by decide +kernel

'''
n=len(ds['beta']['rows'])
gs=[rawperm(g)for g in e['cover_generators']]
a,b=next((i,j)for i,g in enumerate(gs)for j,h in enumerate(gs)if mul(g,h)!=mul(h,g))
s += f'''theorem carrier_nonabelian :
    ∃ x y : Subgroup.closure (Set.range betaGenerators), x*y ≠ y*x := by
  refine ⟨⟨betaGenerators {a}, Subgroup.subset_closure (Set.mem_range_self _)⟩,
    ⟨betaGenerators {b}, Subgroup.subset_closure (Set.mem_range_self _)⟩, ?_⟩
  intro he
  have hne : betaGenerators {a} * betaGenerators {b} ≠
      betaGenerators {b} * betaGenerators {a} := by decide +kernel
  exact hne (congrArg Subtype.val he)

'''
s += f'''/-- The independent displayed C4 rotation is absent from the original
literal carrier. Full coordinate projections therefore do not license
replacement by the full displayed product. -/
theorem independentRotation_not_mem : independentRotation ∉
    Subgroup.closure (Set.range betaGenerators) := by
  intro h
  obtain ⟨i,hi⟩ := (betaCertificate.source_mem_iff _).mp h
  have hno : ∀ i, (betaCertificate.cayley.elements i).1 ≠ independentRotation :=
    {checks(n)}
  exact hno i hi

end SymmetricSubgroupAsymptotics.BinaryChart16T1086
'''
