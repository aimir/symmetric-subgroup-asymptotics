#!/usr/bin/env python3
"""Emit the bounded Schreier/local binding for selected eight-frame row 28.

The input is the already prepared single-row certificate.  This renderer
has no directory scan and emits only the 21-element point stabilizer, its
order-three quotient, eight right-coset representatives, and the Schreier
destination/local-image tables.  Lean rechecks every group and matrix
equation in the generated module.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def lean_array(values: list[int]) -> str:
    return "#[" + ",".join(str(x) for x in values) + "]"


def inverse_permutation(row: tuple[int, ...]) -> tuple[int, ...]:
    result = [0] * len(row)
    for i, x in enumerate(row):
        result[x - 1] = i + 1
    return tuple(result)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("prepared", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    data = json.loads(args.prepared.read_text())
    if data.get("source_row") != 28 or data.get("top_order") != 168:
        raise SystemExit("refusing input other than selected row 28")

    rows = [tuple(r) for r in data["cayley"]["rows"]]
    binding = data["binding"]
    induced = data["induced_binding"]
    # The stored binary basis is coset-major in reverse order: its first two
    # vectors are supported on the eighth affine block, then the seventh, etc.
    representative_rows_raw = [
        rows.index(inverse_permutation(tuple(r)))
        for r in binding["coset_representatives"]
    ]
    representative_rows = list(reversed(representative_rows_raw))

    # Reconstruct the 21-entry local quotient table from the two stored
    # stabilizer generators.  Reuse the bounded verifier used by preparation.
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from prepare_frames8_selected_top_certificate import (
        Budget, paired_hom_enumeration, permutation_rows,
    )
    budget = Budget(1_000_000)
    stabilizer_generators = permutation_rows(binding["stabilizer_generators"], 8, budget)
    local_images = permutation_rows(binding["local_images"], 3, budget)
    hom = paired_hom_enumeration(stabilizer_generators, local_images, 8, 3, budget)
    zero_rows = [tuple(x - 1 for x in r) for r in rows]
    image_values = [(0, 1, 2), (1, 2, 0), (2, 0, 1)]
    exponent = [0] * 168
    stabilizer_rows: list[int] = []
    for row, image in zip(hom["rows"], hom["images"]):
        idx = zero_rows.index(row)
        stabilizer_rows.append(idx)
        raw = image_values.index(image)
        exponent[idx] = (-raw) % 3
    stabilizer_rows.sort()
    if len(stabilizer_rows) != 21:
        raise SystemExit("wrong stabilizer size")

    next_flat = []
    coordinate_forward = []
    for row in induced["coset_next"]:
        forward = [7 - row[7 - a] for a in range(8)]
        coordinate_forward.append(forward)
        next_flat.extend(forward.index(a) for a in range(8))
    # Stored permutations [1,2,3], [2,3,1], [3,1,2] correspond to exponents 0,1,2.
    twist_exp = []
    for j, row in enumerate(induced["twist_local_images"]):
        input_exponents = []
        for b in range(8):
            raw = [(1, 2, 3), (2, 3, 1), (3, 1, 2)].index(tuple(row[7 - b]))
            input_exponents.append((-raw) % 3)
        for a in range(8):
            b = coordinate_forward[j].index(a)
            raw = input_exponents[b]
            twist_exp.append(raw)

    membership = " || ".join(f"i.val = {x}" for x in stabilizer_rows)
    text = f'''import SymmetricSubgroupAsymptotics.PrimitiveAffineEightFrameRow28ModuleRepresentation
import SymmetricSubgroupAsymptotics.PrimitiveAffineEightFrameLocalRowCatalogue
import SymmetricSubgroupAsymptotics.BinaryPlaneOrderThreeRepresentation

/-!
# Selected eight-frame row 28: local quotient and Schreier binding

Generated by `emit_lean_frames8_selected_induced_binding.py`.  Lean checks
the literal 21-element point stabilizer, its onto order-three map, the eight
right cosets, all 24 Schreier equations and local images, and the resulting
sixteen-dimensional generator formula.
-/

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section

namespace SymmetricSubgroupAsymptotics.PrimitiveAffineEightFrameRow28InducedBinding

abbrev Source := PrimitiveAffineEightFrameRow28TopCertificate.Source
local instance sourceGroup : Group Source :=
  PrimitiveAffineEightFrameRow28TopCertificate.group

def inStabilizer (i : Fin 168) : Prop :=
  {membership}

local instance inStabilizerDecidable (i : Fin 168) :
    Decidable (inStabilizer i) := by
  unfold inStabilizer
  infer_instance

private theorem one_inStabilizer :
    inStabilizer (1 : Source).index := by native_decide +revert

private theorem mul_inStabilizer : ∀ x y : Source,
    inStabilizer x.index → inStabilizer y.index →
      inStabilizer (x * y).index := by native_decide +revert

private theorem inv_inStabilizer : ∀ x : Source,
    inStabilizer x.index → inStabilizer x⁻¹.index := by native_decide +revert

/-- The literal 21-element point stabilizer, stored as source-row indices. -/
def sourceStabilizer : Subgroup Source where
  carrier := {{x | inStabilizer x.index}}
  one_mem' := one_inStabilizer
  mul_mem' := by intro x y hx hy; exact mul_inStabilizer x y hx hy
  inv_mem' := by intro x hx; exact inv_inStabilizer x hx

local instance sourceStabilizerMembership (x : Source) :
    Decidable (x ∈ sourceStabilizer) :=
  inStabilizerDecidable x.index

theorem sourceStabilizer_card : Nat.card sourceStabilizer = 21 := by
  rw [Nat.card_eq_fintype_card, Fintype.card_subtype]
  native_decide +revert

private def exponentRow (i : Fin 168) : Fin 3 :=
  ({lean_array(exponent)} : Array (Fin 3))[i.val]!

private theorem exponent_one : exponentRow (1 : Source).index = 0 := by
  native_decide +revert

private theorem exponent_mul : ∀ x y : sourceStabilizer,
    exponentRow (x * y).1.index =
      exponentRow x.1.index + exponentRow y.1.index := by native_decide +revert

abbrev CyclicThree := Multiplicative (ZMod 3)

/-- The stored onto map from the point stabilizer to its cyclic quotient. -/
def sourceLocalMap : sourceStabilizer →* CyclicThree where
  toFun x := Multiplicative.ofAdd (exponentRow x.1.index)
  map_one' := congrArg Multiplicative.ofAdd exponent_one
  map_mul' x y := congrArg Multiplicative.ofAdd (exponent_mul x y)

theorem sourceLocalMap_surjective : Function.Surjective sourceLocalMap := by
  native_decide +revert

private def representativeRows (a : Fin 8) : Fin 168 :=
  ({lean_array(representative_rows)} : Array (Fin 168))[a.val]!

/-- The retained right-coset representatives in the executable top. -/
def representative (a : Fin 8) : Source := ⟨representativeRows a⟩

theorem representative_factor : ∀ x : Source,
    ∃ h : Source, h ∈ sourceStabilizer ∧
      ∃ a : Fin 8, x = h * representative a := by native_decide +revert

private def nextRows (j : Fin 3) (a : Fin 8) : Fin 8 :=
  ({lean_array(next_flat)} : Array (Fin 8))[8 * j.val + a.val]!

def next (j : Fin 3) (a : Fin 8) : Fin 8 := nextRows j a

/-- The literal Schreier twist. -/
def twist (j : Fin 3) (a : Fin 8) : sourceStabilizer :=
  ⟨representative a * PrimitiveAffineEightFrameRow28TopCertificate.ambient j *
      (representative (next j a))⁻¹,
    by fin_cases j <;> fin_cases a <;> native_decide +revert⟩

theorem representative_mul_generator (j : Fin 3) (a : Fin 8) :
    representative a * PrimitiveAffineEightFrameRow28TopCertificate.ambient j =
      (twist j a : Source) * representative (next j a) := by
  simp [twist]

private def twistExponentRows (j : Fin 3) (a : Fin 8) : Fin 3 :=
  ({lean_array(twist_exp)} : Array (Fin 3))[8 * j.val + a.val]!

def twistExponent (j : Fin 3) (a : Fin 8) : Fin 3 := twistExponentRows j a

theorem sourceLocalMap_twist (j : Fin 3) (a : Fin 8) :
    sourceLocalMap (twist j a) =
      Multiplicative.ofAdd (twistExponent j a) := by
  fin_cases j <;> fin_cases a <;> native_decide +revert

private def localForwardColumns (z : CyclicThree) (i : Fin 2) : ℕ :=
  ((if z.toAdd.val < 1 then #[1,2]
    else if z.toAdd.val < 2 then #[3,1] else #[2,3]) : Array ℕ)[i.val]!

private def localInverseColumns (z : CyclicThree) (i : Fin 2) : ℕ :=
  ((if z.toAdd.val < 1 then #[1,2]
    else if z.toAdd.val < 2 then #[2,3] else #[3,1]) : Array ℕ)[i.val]!

def localForwardMatrix (z : CyclicThree) :
    Matrix (Fin 2) (Fin 2) (ZMod 2) :=
  binaryMatrixOfColumnMasks 2 (localForwardColumns z)

def localInverseMatrix (z : CyclicThree) :
    Matrix (Fin 2) (Fin 2) (ZMod 2) :=
  binaryMatrixOfColumnMasks 2 (localInverseColumns z)

def localUnit (z : CyclicThree) :
    Units (Matrix (Fin 2) (Fin 2) (ZMod 2)) :=
  checkedMatrixUnit (localForwardMatrix z) (localInverseMatrix z)
    (by fin_cases z <;> native_decide)
    (by fin_cases z <;> native_decide)

private theorem localUnit_one : localUnit 1 = 1 := by native_decide
private theorem localUnit_mul : ∀ x y : CyclicThree,
    localUnit (x * y) = localUnit x * localUnit y := by
  intro x y
  fin_cases x <;> fin_cases y <;> native_decide

def localMatrixHom : CyclicThree →*
    Units (Matrix (Fin 2) (Fin 2) (ZMod 2)) where
  toFun := localUnit
  map_one' := localUnit_one
  map_mul' := localUnit_mul

def localRepresentation : Representation (ZMod 2) CyclicThree OrderThreeBinaryPlane :=
  matrixUnitRepresentation localMatrixHom

@[simp] theorem localRepresentation_apply (z : CyclicThree) (v : OrderThreeBinaryPlane) :
    localRepresentation z v = (localForwardMatrix z).mulVec v := rfl

theorem localMatrixHom_injective : Function.Injective localMatrixHom := by
  native_decide

theorem localRepresentation_injective : Function.Injective localRepresentation := by
  intro x y hxy
  apply localMatrixHom_injective
  apply Units.ext
  apply Matrix.ext
  intro i j
  have h := LinearMap.congr_fun hxy (Pi.single j 1)
  simpa [localRepresentation, matrixUnitRepresentation,
    Matrix.mulVec, Pi.single_apply] using congrFun h i

private theorem generatorFormula : ∀ (j : Fin 3)
    (v : PrimitiveAffineEightFrameRow28ModuleRepresentation.ModelModule)
    (a : Fin 8) (i : Fin 2),
    PrimitiveAffineEightFrameRow28ModuleRepresentation.representation
        (PrimitiveAffineEightFrameRow28TopCertificate.ambient j) v
        (CoinducedLeadingCoordinates.label a i) =
      localRepresentation (Multiplicative.ofAdd (twistExponent j a))
        (fun q ↦ v (CoinducedLeadingCoordinates.label (next j a) q)) i := by
  native_decide

theorem representation_generator_formula (j : Fin 3)
    (v : PrimitiveAffineEightFrameRow28ModuleRepresentation.ModelModule)
    (a : Fin 8) (i : Fin 2) :
    PrimitiveAffineEightFrameRow28ModuleRepresentation.representation
        (PrimitiveAffineEightFrameRow28TopCertificate.ambient j) v
        (CoinducedLeadingCoordinates.label a i) =
      localRepresentation (Multiplicative.ofAdd (twistExponent j a))
        (fun q ↦ v (CoinducedLeadingCoordinates.label (next j a) q)) i :=
  generatorFormula j v a i

end SymmetricSubgroupAsymptotics.PrimitiveAffineEightFrameRow28InducedBinding

end
'''
    args.output.write_text(text)


if __name__ == "__main__":
    main()
