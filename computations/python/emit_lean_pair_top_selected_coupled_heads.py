#!/usr/bin/env python3
"""Emit one Lean proof of a selected paired-eight coupled-head table."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import tempfile


SCHEMA = "pair-top-selected-coupled-heads-v1"
INPUT_LIMIT = 16 * 1024 * 1024
OUTPUT_LIMIT = 8 * 1024 * 1024
MODULE_RE = re.compile(r"[A-Z][A-Za-z0-9_]*\Z")


class Refused(ValueError):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise Refused(message)


def lookup(values: list[str], variable: str = "i.val", start: int = 0) -> str:
    require(values, "empty Lean lookup")
    if len(values) == 1:
        return values[0]
    middle = len(values) // 2
    return (f"(if {variable} < {start + middle} then "
            f"{lookup(values[:middle], variable, start)} else "
            f"{lookup(values[middle:], variable, start + middle)})")


def lean_nat_array(values: list[int]) -> str:
    return "#[" + ",".join(map(str, values)) + "]"


def read_input(path: Path) -> dict:
    require(path.is_file() and not path.is_symlink(),
            "missing or redirected coupled certificate")
    raw = path.read_bytes()
    require(len(raw) <= INPUT_LIMIT, "coupled certificate ceiling reached")
    value = json.loads(raw)
    require(isinstance(value, dict) and value.get("schema") == SCHEMA,
            "unexpected coupled certificate schema")
    n, g, s = (value.get("degree"), value.get("generator_count"),
               value.get("state_count"))
    require(n == 8 and type(g) is int and 1 <= g <= 16 and
            type(s) is int and 1 <= s <= 256 and value.get("cap") == 4,
            "invalid paired-eight certificate dimensions")
    states = value.get("states")
    heads = value.get("heads")
    displacements = value.get("displacements")
    products = value.get("products")
    denominators = value.get("denominators")
    quotients = value.get("quotient_heads")
    require(isinstance(states, list) and len(states) == s and
            isinstance(heads, list) and len(heads) == s and
            isinstance(displacements, list) and len(displacements) == s and
            isinstance(products, list) and len(products) == s and
            all(isinstance(row, list) and len(row) == s for row in products) and
            isinstance(denominators, list) and
            isinstance(quotients, list) and len(quotients) == s and
            all(isinstance(row, list) and len(row) == s for row in quotients),
            "invalid coupled table shapes")
    dimensions = [len(row) for row in states]
    require(all(0 <= h <= 2 for h in heads) and
            all(len(d.get("basis", [])) == len(d.get("dual", [])) ==
                len(d.get("terms", [])) for d in displacements),
            "invalid displacement rows")
    denominator_map = {}
    for row in denominators:
        p, ell = row.get("product"), row.get("upper")
        require(type(p) is int and type(ell) is int and
                0 <= p < s and 0 <= ell < s and
                (p, ell) not in denominator_map and
                len(row.get("basis", [])) == len(row.get("dual", [])) ==
                len(row.get("terms", [])) and
                row.get("quotient_head") == quotients[p][ell],
                "invalid denominator row")
        denominator_map[p, ell] = row
    require(sum(q is not None for row in quotients for q in row) ==
            len(denominators), "denominator domain mismatch")
    return {**value, "dimensions": dimensions,
            "denominator_map": denominator_map}


def chart(namespace: str, name: str, n: int, row: dict) -> str:
    d = len(row["basis"])
    basis_expr = lookup([str(x) for x in row["basis"]], "j.val") if d else "0"
    dual_expr = lookup([str(x) for x in row["dual"]], "j.val") if d else "0"
    return f"""namespace {namespace}

private def basis (j : Fin {d}) : ℕ := {basis_expr}
private def dual (j : Fin {d}) : ℕ := {dual_expr}

def {name} : BinaryCoordinateSpace {n} {d} :=
  binaryCoordinateSpaceOfMasks {n} {d} basis dual (by decide +kernel +revert)

"""


def emit(module_name: str, natural_module: str, data: dict,
         input_name: str) -> str:
    n, g, s = data["degree"], data["generator_count"], data["state_count"]
    dims = data["dimensions"]
    heads = data["heads"]
    text = f"""import SymmetricSubgroupAsymptotics.{natural_module}
import SymmetricSubgroupAsymptotics.BinaryCoupledHeadCertificate

/-!
# Coupled paired-eight heads for {data['source_id']}

Generated by `emit_lean_pair_top_selected_coupled_heads.py` from
`{input_name}`.  Lean checks the literal retained-generator displacement
spaces, all {s * s} coordinatewise products, all
{len(data['denominators'])} admissible product denominators, and the complete
{data['product_triples']}-triple cap-four inequality.
-/

set_option autoImplicit false
set_option backward.isDefEq.respectTransparency false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option linter.unusedVariables false
set_option linter.unnecessarySeqFocus false
noncomputable section
open scoped BigOperators Classical

namespace SymmetricSubgroupAsymptotics.{module_name}

abbrev Top := {natural_module}.Top
abbrev ModelModule := {natural_module}.ModelModule
abbrev representation := {natural_module}.representation
abbrev topAmbient := {natural_module}.topAmbient
abbrev states := {natural_module}.states
abbrev charts := {natural_module}.charts

"""
    head_theorems = []
    for i, row in enumerate(data["displacements"]):
        d, upper_d = len(row["basis"]), dims[i]
        text += chart(f"D{i}", "displacementChart", n, row)
        text += f"""private theorem space_le_state :
    displacementChart.space ≤ (states {i}).toSubmodule := by
  rw [{natural_module}.states_space]
  apply displacementChart.le_of_basis_mem
  intro j
  decide +kernel +revert

"""
        if d == 0:
            text += f"""noncomputable def certificate :
    BinaryCoordinateDisplacementCertificate representation topAmbient
      (states {i}) displacementChart where
  space_le_state := space_le_state
  termCount := fun j ↦ Fin.elim0 j
  termGenerator := fun j ↦ Fin.elim0 j
  termVector := fun j ↦ Fin.elim0 j
  basis_eq := fun j ↦ Fin.elim0 j

"""
        else:
            terms = row["terms"]
            counts = [len(x) for x in terms]
            generator_rows = [lean_nat_array([x[0] for x in xs]) for xs in terms]
            vector_rows = [lean_nat_array([x[1] for x in xs]) for xs in terms]
            text += f"""private def termCount (j : Fin {d}) : ℕ :=
  {lookup([str(x) for x in counts], 'j.val')}
private def generatorRows (j : Fin {d}) : Array (Fin {g}) :=
  {lookup(generator_rows, 'j.val')}
private def vectorRows (j : Fin {d}) : Array (Fin {upper_d}) :=
  {lookup(vector_rows, 'j.val')}
private def termGenerator (j : Fin {d}) (t : Fin (termCount j)) : Fin {g} :=
  (generatorRows j)[t.val]!
private def termVector (j : Fin {d}) (t : Fin (termCount j)) :
    (states {i}).toSubmodule :=
  ⟨(charts {i}).2.inclusion (Pi.single ((vectorRows j)[t.val]!) 1), by
    rw [{natural_module}.states_space]
    exact ⟨Pi.single ((vectorRows j)[t.val]!) 1, rfl⟩⟩

noncomputable def certificate :
    BinaryCoordinateDisplacementCertificate representation topAmbient
      (states {i}) displacementChart where
  space_le_state := space_le_state
  termCount := termCount
  termGenerator := termGenerator
  termVector := termVector
  basis_eq := by
    intro j
    fin_cases j <;> decide +kernel +revert

"""
        text += f"""theorem head_le :
    Module.finrank (ZMod 2) (states {i}).toRepresentation.Coinvariants ≤
      {heads[i]} := by
  apply representationCoinvariants_finrank_le_of_binaryCertificate
    representation topAmbient (states {i}) displacementChart certificate
  rw [{natural_module}.states_space, (charts {i}).2.finrank]
  decide +kernel +revert

end D{i}

"""
        head_theorems.append(f"D{i}.head_le")

    product_certificates = []
    for i, row in enumerate(data["products"]):
        for j, product in enumerate(row):
            p = product["state"]
            terms = product["terms"]
            pdim = dims[p]
            namespace = f"P{i}_{j}"
            text += f"""namespace {namespace}

"""
            if pdim == 0:
                text += f"""noncomputable def certificate :
    BinaryCoordinateProductCertificate
      (charts {i}).2 (charts {j}).2 (charts {p}).2 where
  products_mem := by
    intro a b
    decide +kernel +revert
  termCount := fun q ↦ Fin.elim0 q
  leftIndex := fun q ↦ Fin.elim0 q
  rightIndex := fun q ↦ Fin.elim0 q
  basis_eq := fun q ↦ Fin.elim0 q

"""
            else:
                counts = [len(x) for x in terms]
                left_rows = [lean_nat_array([x[0] for x in xs]) for xs in terms]
                right_rows = [lean_nat_array([x[1] for x in xs]) for xs in terms]
                text += f"""private def termCount (q : Fin {pdim}) : ℕ :=
  {lookup([str(x) for x in counts], 'q.val')}
private def leftRows (q : Fin {pdim}) : Array (Fin {dims[i]}) :=
  {lookup(left_rows, 'q.val')}
private def rightRows (q : Fin {pdim}) : Array (Fin {dims[j]}) :=
  {lookup(right_rows, 'q.val')}
private def leftIndex (q : Fin {pdim}) (t : Fin (termCount q)) : Fin {dims[i]} :=
  (leftRows q)[t.val]!
private def rightIndex (q : Fin {pdim}) (t : Fin (termCount q)) : Fin {dims[j]} :=
  (rightRows q)[t.val]!

noncomputable def certificate :
    BinaryCoordinateProductCertificate
      (charts {i}).2 (charts {j}).2 (charts {p}).2 where
  products_mem := by
    intro a b
    decide +kernel +revert
  termCount := termCount
  leftIndex := leftIndex
  rightIndex := rightIndex
  basis_eq := by
    intro q
    fin_cases q <;> decide +kernel +revert

"""
            text += f"""end {namespace}

"""
            product_certificates.append(f"{namespace}.certificate")

    product_table = "#[" + ",".join(
        lean_nat_array(row) for row in data["product_state_table"]) + "]"
    text += f"""private def productStateTable : Array (Array (Fin {s})) :=
  {product_table}

def productState (i j : Fin {s}) : Fin {s} :=
  (productStateTable[i.val]!)[j.val]!

noncomputable def productCertificate (i j : Fin {s}) :
    BinaryCoordinateProductCertificate
      (charts i).2 (charts j).2 (charts (productState i j)).2 := by
  rcases i with ⟨i, hi⟩
  interval_cases i <;> rcases j with ⟨j, hj⟩ <;> interval_cases j
"""
    text += "\n".join(f"  · exact {name}" for name in product_certificates)
    text += f"""

theorem product_eq (i j : Fin {s}) :
    binaryCoordinateProductSpan (states i).toSubmodule
        (states j).toSubmodule =
      (states (productState i j)).toSubmodule := by
  rw [{natural_module}.states_space, {natural_module}.states_space,
    {natural_module}.states_space]
  exact (productCertificate i j).span_eq

"""

    quotient_names = {}
    for row in data["denominators"]:
        p, ell = row["product"], row["upper"]
        d, pdim, ldim = len(row["basis"]), dims[p], dims[ell]
        q = row["quotient_head"]
        namespace = f"Q{p}_{ell}"
        text += chart(namespace, "denominatorChart", n, row)
        product_inclusion_proof = ("" if p == ell else
            f"  apply (charts {p}).2.le_of_basis_mem\n"
            "  intro j\n  decide +kernel +revert\n")
        text += f"""private theorem product_le_upper :
    (charts {p}).2.space ≤ (states {ell}).toSubmodule := by
  rw [{natural_module}.states_space]
{product_inclusion_proof}
private theorem space_le_state :
    denominatorChart.space ≤ (states {ell}).toSubmodule := by
  rw [{natural_module}.states_space]
  apply denominatorChart.le_of_basis_mem
  intro j
  decide +kernel +revert

"""
        if d == 0:
            text += f"""noncomputable def certificate :
    BinaryCoordinateCoupledDenominatorCertificate representation topAmbient
      (states {ell}) (charts {p}).2 product_le_upper denominatorChart where
  space_le_state := space_le_state
  termCount := fun j ↦ Fin.elim0 j
  term := fun j ↦ Fin.elim0 j
  basis_eq := fun j ↦ Fin.elim0 j

"""
        else:
            terms = row["terms"]
            counts = [len(x) for x in terms]
            option_rows, generator_rows, vector_rows = [], [], []
            for xs in terms:
                options, generators, vectors = [], [], []
                for term in xs:
                    if term[0] == 0:
                        options.append(f"some {term[1]}")
                        generators.append(0)
                        vectors.append(0)
                    else:
                        options.append("none")
                        generators.append(term[1])
                        vectors.append(term[2])
                option_rows.append("#[" + ",".join(options) + "]")
                generator_rows.append(lean_nat_array(generators))
                vector_rows.append(lean_nat_array(vectors))
            text += f"""private def termCount (j : Fin {d}) : ℕ :=
  {lookup([str(x) for x in counts], 'j.val')}
private def productRows (j : Fin {d}) : Array (Option (Fin {pdim})) :=
  {lookup(option_rows, 'j.val')}
private def generatorRows (j : Fin {d}) : Array (Fin {g}) :=
  {lookup(generator_rows, 'j.val')}
private def vectorRows (j : Fin {d}) : Array (Fin {ldim}) :=
  {lookup(vector_rows, 'j.val')}
private def termVector (j : Fin {d}) (t : Fin (termCount j)) :
    (states {ell}).toSubmodule :=
  ⟨(charts {ell}).2.inclusion (Pi.single ((vectorRows j)[t.val]!) 1), by
    rw [{natural_module}.states_space]
    exact ⟨Pi.single ((vectorRows j)[t.val]!) 1, rfl⟩⟩
private def term (j : Fin {d}) (t : Fin (termCount j)) :
    Fin {pdim} ⊕ (Fin {g} × (states {ell}).toSubmodule) :=
  match (productRows j)[t.val]! with
  | some i => Sum.inl i
  | none => Sum.inr ((generatorRows j)[t.val]!, termVector j t)

noncomputable def certificate :
    BinaryCoordinateCoupledDenominatorCertificate representation topAmbient
      (states {ell}) (charts {p}).2 product_le_upper denominatorChart where
  space_le_state := space_le_state
  termCount := termCount
  term := term
  basis_eq := by
    intro j
    fin_cases j <;> decide +kernel +revert

"""
        text += f"""theorem quotient_le
    (h : (states {p}).toSubmodule ≤ (states {ell}).toSubmodule) :
    Module.finrank (ZMod 2)
        ((states {ell}).toSubmodule ⧸
          binaryCoupledDenominator representation topAmbient (states {ell})
            (states {p}).toSubmodule h) ≤ {q} := by
  simpa only [{natural_module}.states_space] using
    (binaryCoupledQuotient_finrank_le_of_binaryCertificate
      representation topAmbient (states {ell}) (charts {p}).2
      product_le_upper denominatorChart certificate (by
        rw [{natural_module}.states_space, (charts {ell}).2.finrank]
        decide +kernel +revert))

end {namespace}

"""
        quotient_names[p, ell] = f"{namespace}.quotient_le"

    head_lookup = lookup([str(x) for x in heads])
    quotient_arrays = []
    for row in data["quotient_heads"]:
        quotient_arrays.append(lean_nat_array([0 if x is None else x for x in row]))
    quotient_table = "#[" + ",".join(quotient_arrays) + "]"
    text += f"""def head (i : Fin {s}) : ℕ := {head_lookup}

theorem head_le (i : Fin {s}) :
    Module.finrank (ZMod 2) (states i).toRepresentation.Coinvariants ≤
      head i := by
  fin_cases i
"""
    text += "\n".join(f"  · exact {name}" for name in head_theorems)
    text += f"""

private def quotientHeadTable : Array (Array ℕ) := {quotient_table}

def quotientHead (p ell : Fin {s}) : ℕ :=
  (quotientHeadTable[p.val]!)[ell.val]!

theorem quotient_le (p ell : Fin {s})
    (h : (states p).toSubmodule ≤ (states ell).toSubmodule) :
    Module.finrank (ZMod 2)
      ((states ell).toSubmodule ⧸
        binaryCoupledDenominator representation topAmbient (states ell)
          (states p).toSubmodule h) ≤ quotientHead p ell := by
  rcases p with ⟨p, hp⟩
  interval_cases p <;> rcases ell with ⟨ell, hell⟩ <;> interval_cases ell
"""
    for p in range(s):
        for ell in range(s):
            if (p, ell) in quotient_names:
                text += f"  · exact {quotient_names[p, ell]} h\n"
            else:
                witness = next(index for index, value in enumerate(data["states"][p])
                               if value not in [] and not _contained_mask(
                                   value, data["states"][ell]))
                text += f"""  · exfalso
    rw [{natural_module}.states_space, {natural_module}.states_space] at h
    exact ((charts {p}).2.not_le_of_basis_not_mem
      (charts {ell}).2.space ⟨{witness}, by decide +kernel⟩ (by decide +kernel +revert)) h
"""
    text += f"""
/-- Complete checked coupled-head registry for this literal paired-eight
top action. -/
noncomputable def registry :
    BinaryInvariantCoupledHeadRegistry representation topAmbient states 4 where
  head := head
  head_le := head_le
  productState := productState
  product_eq := product_eq
  quotientHead := quotientHead
  quotient_le := quotient_le
  coupled_le := by
    intro i j ell _h
    fin_cases i <;> fin_cases j <;> fin_cases ell <;> decide +kernel +revert

/-- The finite coupled-head table together with the independently checked
cyclic-orbit proof that its state list contains every invariant submodule. -/
noncomputable def completeRegistry :
    BinaryInvariantCompleteCoupledHeadRegistry
      representation topAmbient states 4 where
  coupled := registry
  complete := {natural_module}.registry.complete

end SymmetricSubgroupAsymptotics.{module_name}

end
"""
    return text


def _contained_mask(value: int, rows: list[int]) -> bool:
    for row in reversed(rows):
        if (value >> (row.bit_length() - 1)) & 1:
            value ^= row
    return value == 0


def write_atomic(path: Path, payload: bytes, force: bool) -> None:
    require(force or not path.exists(), "output exists; use --force")
    require(len(payload) <= OUTPUT_LIMIT, "Lean output byte ceiling reached")
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("wb", delete=False, dir=path.parent,
                                     prefix=path.name + ".",
                                     suffix=".partial") as stream:
        temporary = Path(stream.name)
        stream.write(payload)
    try:
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--module", required=True)
    parser.add_argument("--natural-module", required=True)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    for name in (args.module, args.natural_module):
        require(MODULE_RE.fullmatch(name) is not None, "invalid Lean module")
    data = read_input(args.input)
    payload = emit(args.module, args.natural_module, data,
                   args.input.name).encode()
    write_atomic(args.output, payload, args.force)
    print(args.output, len(payload), "bytes", data["source_id"])
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, KeyError, TypeError, StopIteration,
            json.JSONDecodeError, Refused) as error:
        raise SystemExit(f"refused: {error}")
