class CertificateError(Exception):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise CertificateError(message)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class Budget:
    def __init__(self, rows: int, operations: int, seconds: float):
        self.max_rows = rows
        self.max_operations = operations
        self.seconds = seconds
        self.started = time.monotonic()
        self.operations = 0

    def check_time(self) -> None:
        require(time.monotonic() - self.started <= self.seconds,
                "selected time ceiling reached; no certificate published")

    def charge(self, amount: int = 1) -> None:
        self.operations += amount
        require(self.operations <= self.max_operations,
                "selected operation ceiling reached; no certificate published")
        self.check_time()


def bounded_read(path: Path, limit: int) -> bytes:
    require(path.is_file() and not path.is_symlink(), f"not a regular input file: {path}")
    with path.open("rb") as handle:
        data = handle.read(limit + 1)
    require(len(data) <= limit, f"input byte ceiling reached: {path}")
    return data


def read_header() -> bytes:
    require(INPUT.is_file() and not INPUT.is_symlink(), "missing/redirected catalogue input")
    with gzip.open(INPUT, "rb") as handle:
        data = handle.readline(MAX_HEADER_BYTES + 1)
    require(0 < len(data) <= MAX_HEADER_BYTES and data.endswith(b"\n"),
            "catalogue header exceeds the fixed 1 MiB ceiling or is incomplete")
    require(sha256(data) == HEADER_SHA256, "pinned catalogue header SHA256 mismatch")
    return data


def selected_generators(label: str, header: bytes, budget: Budget) -> list[tuple[int, ...]]:
    selection = SELECTIONS[label]
    decoded = json.loads(header)
    require(isinstance(decoded, dict) and isinstance(decoded.get("nodes"), list),
            "catalogue header must contain a node list")
    matches = []
    for node in decoded["nodes"]:
        budget.charge()
        require(isinstance(node, dict), "malformed catalogue node")
        if node.get("id") == label:
            matches.append(node)
    require(len(matches) == 1, "selected original label is missing or duplicated")
    node = matches[0]
    canonical = json.dumps(node, sort_keys=True, separators=(",", ":")).encode()
    require(sha256(canonical) == selection.node_sha256, "pinned selected-node SHA256 mismatch")
    require(node.get("degree") == 16, "selected node has the wrong original degree")
    raw = node.get("generators")
    require(isinstance(raw, list) and len(raw) == selection.generator_count,
            "original generator tuple length differs from the pinned selection")
    result = []
    for row in raw:
        budget.charge(16)
        require(isinstance(row, list) and len(row) == 16
                and all(type(x) is int for x in row)
                and sorted(row) == list(range(1, 17)), "invalid original generator permutation")
        result.append(tuple(x - 1 for x in row))
    # Deliberately never read node['order']; only the eventual Lean theorem
    # establishes a bound for the original subgroup.
    return result


def search(generators: list[tuple[int, ...]], budget: Budget) -> dict:
    """Linear generator-edge BFS; never visit a pair of arbitrary group rows."""
    identity = tuple(range(16))
    rows = [identity]
    indices = {identity: 0}
    parents, letters, transitions = [0], [0], []
    i = 0
    while i < len(rows):
        edges = []
        for j, generator in enumerate(generators):
            budget.charge(17)  # sixteen image entries and one dictionary lookup
            product = tuple(rows[i][generator[x]] for x in range(16))
            target = indices.get(product)
            if target is None:
                require(len(rows) < budget.max_rows,
                        "selected row ceiling reached; closure is not certified")
                budget.charge(3)  # row, parent, and generator-label insertion
                target = len(rows)
                indices[product] = target
                rows.append(product)
                parents.append(i)
                letters.append(j)
            edges.append(target)
        transitions.append(edges)
        i += 1
    codes = []
    for row in rows:
        budget.charge(16)
        codes.append(sum(value * 16 ** point for point, value in enumerate(row)))
    # Lightweight producer-side validation supplements, and never replaces,
    # the original-action equations proved by the emitted Lean source.
    for i in range(1, len(rows)):
        budget.charge()
        require(parents[i] < i and transitions[parents[i]][letters[i]] == i,
                "internal BFS predecessor mismatch")
    return {"codes": codes, "parents": parents, "letters": letters, "next": transitions}


def lookup(values: list[int], index: str, start: int = 0) -> str:
    require(bool(values), "empty finite lookup")
    if len(values) == 1:
        return str(values[0])
    split = len(values) // 2
    return (f"(if {index} < {start + split} then {lookup(values[:split], index, start)} "
            f"else {lookup(values[split:], index, start + split)})")


def packed_lookup(values: list[int], index: str = "i.val") -> str:
    """At most 32 fixed-width digits per integer, with balanced block lookup."""
    bits = max(1, max(values).bit_length())
    chunks = [sum(value << (bits * j) for j, value in enumerate(values[i:i + 32]))
              for i in range(0, len(values), 32)]
    expression = lookup(chunks, f"({index}) / 32")
    return f"(({expression} : ℕ) / 2 ^ ({bits} * (({index}) % 32)) % 2 ^ {bits})"


def assemble_checks(names: list[str]) -> str:
    """Balanced dependent Fin elimination, reusing separately checked rows."""
    if len(names) == 1:
        return f"(Fin.cases {names[0]} (fun i => Fin.elim0 i))"
    split = len(names) // 2
    return (f"(Fin.addCases (m := {split}) (n := {len(names) - split}) "
            f"{assemble_checks(names[:split])} {assemble_checks(names[split:])})")


def emit(label: str, table: dict, budget: Budget) -> bytes:
    selection = SELECTIONS[label]
    n = len(table["codes"])
    require(1 <= n <= MAX_ROWS, "invalid finite row count")
    g = selection.generator_count
    generator_word = "two" if g == 2 else str(g)
    budget.charge(n * (3 + g))
    names = [f"row_checked_{i:03d}" for i in range(n)]
    proofs = "\n".join(
        f"private theorem {name} : RowChecked {i} := by unfold RowChecked; decide +kernel\n"
        for i, name in enumerate(names))
    next_values = [target for row in table["next"] for target in row]
    source = f'''import SymmetricSubgroupAsymptotics.FinitePermutationEncoding
import SymmetricSubgroupAsymptotics.GeneratedAction16.DataChunk{selection.chunk}

/-!
# Selected original-action order stop: 16T{selection.master}

Generated by export_lean_schreier_order_stop.py from the pinned original
generator tuple, in its original order. There are {n} rows and {generator_word} outgoing
generator edges per row; no dense multiplication table is used. Each local
check is a separate declaration, under the default heartbeat limit.
Parent edges construct actual original words. The order bound follows from
their surjection onto the literal closure, not from a catalogue order field.
This is one order-stop certificate, not registry or carrier coverage.
-/

set_option autoImplicit false
set_option maxRecDepth 4096
noncomputable section

namespace SymmetricSubgroupAsymptotics.BinaryPrunedOrder16T{selection.master}

abbrev generators : Fin {g} → Equiv.Perm (Fin 16) :=
  BinaryActionData16.node{selection.master}Generators

abbrev Original : Subgroup (Equiv.Perm (Fin 16)) :=
  Subgroup.closure (Set.range generators)

private def codes (i : Fin {n}) : Fin (16 ^ 16) :=
  Fin.ofNat (16 ^ 16) {packed_lookup(table['codes'])}

private def parents (i : Fin {n}) : Fin {n} :=
  Fin.ofNat {n} {packed_lookup(table['parents'])}

private def letters (i : Fin {n}) : Fin {g} :=
  Fin.ofNat {g} {packed_lookup(table['letters'])}

private def nextRow (i : Fin {n}) (j : Fin {g}) : Fin {n} :=
  Fin.ofNat {n} {packed_lookup(next_values, f'i.val * {g} + j.val')}

private def RowChecked (i : Fin {n}) : Prop :=
  (∀ j : Fin {g}, codes (nextRow i j) =
    (permutationGeneratorEncoding generators).step (codes i) j) ∧
  (i ≠ 0 → (parents i).val < i.val) ∧
  (i ≠ 0 → nextRow (parents i) (letters i) = i)

{proofs}
private theorem rows_checked : ∀ i : Fin {n}, RowChecked i :=
  {assemble_checks(names)}

def certificate : EncodedCayleyCertificate
    (permutationGeneratorEncoding generators) {n} where
  rows := codes
  identity := 0
  identity_eq := by decide +kernel
  next := nextRow
  next_eq i := (rows_checked i).1
  rank i := i.val
  parent i _ := parents i
  letter i _ := letters i
  parent_lt i hi := (rows_checked i).2.1 hi
  parent_next i hi := (rows_checked i).2.2 hi

/-- Actual original subgroup order, obtained from a certified row surjection. -/
theorem card_le_rowCount : Nat.card Original ≤ {n} := by
  let f : Fin {n} → Original := fun i =>
    ⟨certificate.toCayley.elements i,
      (certificate.toCayley.mem_closure_iff _).mpr ⟨i, rfl⟩⟩
  have hf : Function.Surjective f := by
    rintro ⟨g, hg⟩
    obtain ⟨i, hi⟩ := (certificate.toCayley.mem_closure_iff g).mp hg
    exact ⟨i, Subtype.ext hi⟩
  simpa only [Nat.card_fin] using Nat.card_le_card_of_surjective f hf

/-- The source boundary for pruning index-two children at order 128. -/
theorem card_le : Nat.card Original ≤ 256 :=
  card_le_rowCount.trans (by decide)

end SymmetricSubgroupAsymptotics.BinaryPrunedOrder16T{selection.master}
'''
    budget.check_time()
    return source.encode("utf-8")


def canonical_output(selection: Selection) -> Path:
    path = FORMAL / "GeneratedPrunedActions" / f"Order16T{selection.master}.lean"
    require(path.resolve().is_relative_to(FORMAL.resolve()), "canonical output escapes formal tree")
    require(not path.is_symlink(), "refusing a symbolic-link output")
    for parent in path.parents:
        if parent == ROOT:
            break
        require(not parent.is_symlink(), "refusing a symbolic-link output directory")
    return path


def report_path(raw: str | None) -> Path | None:
    if raw is None:
        return None
    path = Path(raw).expanduser()
    require(path.is_absolute() and path.suffix == ".json", "report needs an absolute .json path")
    require(not path.is_symlink(), "refusing a symbolic-link report")
    path = path.resolve()
    require(not path.is_relative_to(ROOT.resolve()), "report must be outside the repository")
    require(path.parent.is_dir(), "report parent directory must already exist")
    return path


def atomic_write(path: Path, data: bytes) -> None:
    require(not path.is_symlink(), "refusing a symbolic-link write")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(prefix=f".{path.name}.", dir=path.parent,
                                         delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", required=True, choices=tuple(SELECTIONS))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Atomically install one canonical source.")
    mode.add_argument("--check", action="store_true", help="Read-only exact-byte replay.")
    parser.add_argument("--report", help="Optional bounded JSON audit outside the repository.")
    parser.add_argument("--max-rows", type=int, default=MAX_ROWS)
    parser.add_argument("--max-operations", type=int, default=MAX_OPERATIONS)
    parser.add_argument("--max-seconds", type=float, default=MAX_SECONDS)
    parser.add_argument("--max-output-bytes", type=int, default=MAX_OUTPUT_BYTES)
    args = parser.parse_args()
    require(1 <= args.max_rows <= MAX_ROWS, "row limit must be in 1..256")
    require(1 <= args.max_operations <= MAX_OPERATIONS, "operation limit exceeds immutable ceiling")
    require(math.isfinite(args.max_seconds) and 0 < args.max_seconds <= MAX_SECONDS,
            "time limit must be finite and in (0, 5]")
    require(1 <= args.max_output_bytes <= MAX_OUTPUT_BYTES, "output limit exceeds immutable ceiling")
    require(not (args.check and args.report), "--check is read-only and cannot write a report")
    report = report_path(args.report)
    budget = Budget(args.max_rows, args.max_operations, args.max_seconds)
    selection = SELECTIONS[args.source]
    output = canonical_output(selection)
    producer_bytes = bounded_read(SELF, MAX_SOURCE_BYTES)
    chunk_path = FORMAL / "GeneratedAction16" / f"DataChunk{selection.chunk}.lean"
    chunk_bytes = bounded_read(chunk_path, MAX_SOURCE_BYTES)
    require(sha256(chunk_bytes) == selection.chunk_sha256, "pinned original Lean generator source changed")
    header = read_header()
    generators = selected_generators(args.source, header, budget)
    table = search(generators, budget)
    lean = emit(args.source, table, budget)
    require(len(lean) <= args.max_output_bytes, "generated Lean exceeds output ceiling")
    summary = {
        "schema": "selected-original-action-order-stop-v1",
        "source": args.source,
        "original_index_metadata_only": selection.original_index,
        "original_degree": 16,
        "original_generator_count": selection.generator_count,
        "rows": len(table["codes"]),
        "generator_edges": len(table["codes"]) * selection.generator_count,
        "charged_operations": budget.operations,
        "operation_unit": "point-image, lookup, insertion, node-validation or syntax-table entry",
        "lean_path": str(output.relative_to(ROOT)),
        "lean_bytes": len(lean),
        "lean_sha256": sha256(lean),
        "producer_sha256": sha256(producer_bytes),
        "header_sha256": sha256(header),
        "selected_node_sha256": selection.node_sha256,
        "original_generator_source_sha256": sha256(chunk_bytes),
        "limits": {"rows": args.max_rows, "operations": args.max_operations,
                   "seconds": args.max_seconds, "output_bytes": args.max_output_bytes,
                   "header_bytes": MAX_HEADER_BYTES},
        "proof_status": "candidate only; requires original-source Lean check",
        "no_claims": ["exact order", "high-order registry completeness", "global action coverage",
                      "normal-subgroup coverage", "carrier coverage"],
    }
    report_bytes = (json.dumps(summary, indent=2, sort_keys=True) + "\n").encode()
    require(len(lean) + (len(report_bytes) if report else 0) <= args.max_output_bytes,
            "combined Lean/report output exceeds ceiling")
    # Guard every source snapshot after all candidate computation and before
    # any publication. Replay performs these same checks without writes.
    require(bounded_read(SELF, MAX_SOURCE_BYTES) == producer_bytes, "producer changed during run")
    require(bounded_read(chunk_path, MAX_SOURCE_BYTES) == chunk_bytes, "original generator source changed during run")
    require(read_header() == header, "catalogue header changed during run")
    budget.check_time()
    if args.check:
        require(bounded_read(output, args.max_output_bytes) == lean,
                f"generated witness differs: {output.relative_to(ROOT)}")
        status = "byte-identical"
    elif args.write:
        atomic_write(output, lean)
        status = "written"
    else:
        status = "candidate-only"
    if report is not None:
        atomic_write(report, report_bytes)
    print(f"{args.source}: {status}; {len(table['codes'])} rows; "
          f"{budget.operations} charged operations; {len(lean)} Lean bytes; {sha256(lean)}")


if __name__ == "__main__":
    try:
        main()
    except (CertificateError, OSError, ValueError, TypeError, KeyError) as error:
        raise SystemExit(f"order-stop certificate refused: {error}") from None
