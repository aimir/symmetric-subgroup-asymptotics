#!/usr/bin/env python3
"""Emit one explicitly selected bounded original-action order-stop certificate.

Required selection, with no bulk/default action:
  python3 -B computations/python/export_lean_schreier_order_stop.py \
    --source b16_524 --write --report /private/path/order-stop-524.json
  python3 -B computations/python/export_lean_schreier_order_stop.py \
    --source b16_524 --check

With neither --write nor --check, search and print a summary without installing
Lean source. --check is strictly read-only and rejects --report. Reports must
be outside the repository. Only the bounded first gzip line is read; no action
or normal-subgroup records are scanned. The catalogue's declared order is NOT
used to establish the bound. Lean checks closure under every original
generator and parent-word reachability, giving an actual surjection onto the
literal generated subgroup. Injectivity and dense multiplication are unneeded.

Immutable ceilings: 256 rows, 100000 charged operations, 5 seconds, 128 KiB
combined generated Lean/report output, and a 1 MiB uncompressed header. Command
line limits can only lower these ceilings. Time limits are cooperative, not
hard process preemption or an RSS guarantee. No compiler, subprocess, external
exporter, GAP, network, inverse table, or dense multiplication table is used.
Generated bytes are candidates until their bounded Lean checks pass.
"""
