#!/usr/bin/env python3
"""Emit one explicitly selected 64-element degree-eight normal registry.

No catalogue or GAP call. Enumerates central-involution extensions only;
Lean independently checks all quotient rows/children and derives completeness.
Uses bounded table/emission functions of the retained selected sparse emitter;
never calls either legacy main. Each invocation selects exactly one source.

Requires --root and --output-dir; never defaults to the formal source tree.
Receipts go to stdout and optionally an explicit --receipt outside --root.
Public function-only dependencies in computations/python are
export_lean_normal_registry.py, export_lean_carrier_normal_registry_selected.py,
and (transitively) export_lean_menu_cayley.py. No preparation-script dependency.
The historical generated Lean headers are preserved for byte comparison.
Caps:64 source rows,128 normal states,3 million cooperative operations,
30 seconds cooperative time,2 MiB total output. Generated sources still need
the primary agent's serialized capped Lean checks.
"""
from pathlib import Path
from types import SimpleNamespace
import argparse,re,sys,time,json,hashlib
ap=argparse.ArgumentParser();ap.add_argument('--master',required=True,choices=['8T28','8T29','8T31']);ap.add_argument('--root',required=True,type=Path);ap.add_argument('--output-dir',required=True,type=Path);ap.add_argument('--receipt',type=Path);a=ap.parse_args()
a.root=a.root.resolve();a.output_dir=a.output_dir.resolve()
if a.receipt and a.receipt.resolve().is_relative_to(a.root):ap.error('--receipt must be outside --root')
sys.path.insert(0,str(a.root/'computations/python'))
import export_lean_normal_registry as legacy
import export_lean_carrier_normal_registry_selected as sparse
budget=sparse.Budget(operations=3000000,seconds=30,output_bytes=2000000)
p=a.root/'formal/SymmetricSubgroupAsymptotics';
with (p/f'BinaryMenuCayley{a.master}.lean').open('rb') as stream:src=stream.read(100001)
if len(src)>100000:raise RuntimeError('selected input byte cap exceeded')
perms=[tuple(map(int,x.split(','))) for x in re.findall(r'toFun x := \(#\[([0-9,]+)\]',src.decode())];assert 1<=len(perms)<=5
spec=SimpleNamespace(master=a.master,source_rows=64,normal_count=128,order_log=6,source_module='BinaryMenuCayley'+a.master,namespace='SymmetricSubgroupAsymptotics.RDTBinaryNormal'+a.master)
legacy.table=sparse.bounded_table_factory(spec,budget);legacy.compose=budget.compose
st=legacy.table(perms,8);G=[legacy.unpack(c,8) for c in st['codes']];assert len(G)==64
e=tuple(range(8));normals=[dict(elements=frozenset([e]),gens=[],children=set())];lookup={normals[0]['elements']:0}
for N in normals:
 for x in G:
  budget.tick()
  if x in N['elements'] or budget.compose(x,x) not in N['elements']:continue
  if not all(budget.compose(budget.compose(x,g),legacy.inv(budget.compose(g,x))) in N['elements'] for g in perms):continue
  K=N['elements']|frozenset(budget.compose(y,x) for y in N['elements'])
  assert len(K)==2*len(N['elements'])
  if K not in lookup:
   assert len(normals)<128
   lookup[K]=len(normals);normals.append(dict(elements=K,gens=N['gens']+[x],children=set()))
  N['children'].add(lookup[K]+1)
record={'normals':[{'normal_generators':[[x+1 for x in g] for g in N['gens']],'children':sorted(N['children']),'order':len(N['elements'])} for N in normals]}
node={'id':'b8_'+a.master.split('T')[1],'degree':8,'generators':[[x+1 for x in g] for g in perms]}
spec.normal_count=len(normals)
_,states=legacy.emit(node,record)
states=states.replace('SymmetricSubgroupAsymptotics.BinaryNormal'+a.master,spec.namespace).replace('set_option maxHeartbeats 0','set_option Elab.async false').replace('Generated by export_lean_normal_registry.py','Selected by external selected_missing_normal_registry.py')
data=legacy.action_data(node,record)
registry=sparse.emit_registry(spec,data,budget).replace('SymmetricSubgroupAsymptotics.GeneratedCarrierNormal'+a.master+'.States','SymmetricSubgroupAsymptotics.GeneratedRDTNormal'+a.master+'.States')
lines=registry.splitlines()
for i,line in enumerate(lines):
 if re.match(r'private def child(?:Rows|Index)\d+ \(j : Fin \d+\)',line) and not re.search(r'\bj\b',line.split(':=',1)[1]):
  lines[i]=line.replace('(j :','(_j :',1)
registry='\n'.join(lines)+'\n'
assert len(states.encode())+len(registry.encode())<2000000
out=a.output_dir;out.mkdir(parents=True,exist_ok=True)
(out/'States.lean').write_text(states);(out/'Registry.lean').write_text(registry)
receipt={'master':a.master,'source_sha256':hashlib.sha256(src).hexdigest(),'source_rows':len(G),'normal_states':len(normals),'normal_row_total':sum(len(N['elements']) for N in normals),'operations':budget.operations,'seconds':time.monotonic()-budget.started,'states_bytes':len(states.encode()),'registry_bytes':len(registry.encode()),'normal_generators':record['normals']}
receipt['states_sha256']=hashlib.sha256(states.encode()).hexdigest()
receipt['registry_sha256']=hashlib.sha256(registry.encode()).hexdigest()
receipt_text=json.dumps(receipt,sort_keys=True,indent=2)+'\n'
if a.receipt:
 a.receipt.parent.mkdir(parents=True,exist_ok=True)
 a.receipt.write_text(receipt_text)
print(receipt_text,end='')
