#!/usr/bin/env python3
"""Emit quotient-socle certificates for one selected nonbinary action.

The inputs are the complete normal chunks already consumed by
``emit_lean_nonbinary_selected_normals.py``.  Each chunk carries a relative
socle carrier and a short path of conjugacy-class representatives.  This
emitter re-derives that plan from the pinned literal subgroups, then emits
only indices.  Lean rechecks relative minimality, the carrier supremum, and
the normal-closure equation on the executable Cayley group before the data
are transported to the literal permutation subgroup.

There is no directory scan or bulk mode.  The script never invokes Lean,
GAP, a subprocess, or another exporter.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True

from emit_lean_nonbinary_selected_normals import (
    MODULE_RE,
    Refused,
    enumerate_group,
    fin_cases_chain,
    permutation,
    read_chunk,
    read_pinned_data,
    require,
    validate_and_prepare,
    write_atomic,
)
from export_lean_nonbinary_selected_chunks import (
    Refused as PlanRefused,
    relative_socle_plan,
)


OUTPUT_LIMIT = 512 * 1024


def validated_plans(prepared: dict) -> list[dict]:
    action = read_pinned_data()[prepared["action_id"]]
    normal_sets = [
        frozenset(enumerate_group([permutation(row)
                                  for row in normal["generators"]]))
        for normal in action["normals"]
    ]
    expected = [relative_socle_plan(action, normal_sets, i)
                for i in range(len(normal_sets))]
    actual = [row.get("relative_socle") for row in prepared["records"]]
    require(actual == expected,
            "relative-socle plans disagree with the pinned literal lattice")
    return expected


def emit_module(module: str, class_module: str, normal_module: str,
                structural_module: str, prepared: dict,
                plans: list[dict], input_names: list[str]) -> str:
    normal_count = len(plans)
    require(1 <= normal_count <= 128,
            "selected normal count outside the quotient-socle ceiling")
    generator_bound = max(1, max(len(plan["generator_class_indices"])
                                 for plan in plans))
    require(generator_bound <= 8,
            "relative socle needs more than eight selected generators")
    carrier_values = [str(plan["carrier_state_index"] - 1)
                      for plan in plans]

    generator_names = []
    generator_definitions = []
    for i, plan in enumerate(plans):
        classes = plan["generator_class_indices"]
        values = [f"representative {j - 1}" for j in classes]
        values.extend(["(1 : Source)"] * (generator_bound - len(values)))
        name = f"state{i}SocleGenerators"
        generator_names.append(name)
        generator_definitions.append(
            f"private def {name} : Fin {generator_bound} → Source :=\n"
            f"  {fin_cases_chain(values)}\n")

    text = f"""import SymmetricSubgroupAsymptotics.FiniteNormalRegistryQuotientSocle
import SymmetricSubgroupAsymptotics.PrimitiveAffineDegreeTwoBinaryKernelAnchor
import SymmetricSubgroupAsymptotics.{structural_module}

/-!
# Quotient socles for selected nonbinary action {prepared['action_id']}

Generated by `emit_lean_nonbinary_selected_quotient_socles.py` from the
explicit checked normal chunks `{', '.join(input_names)}`.  The generator
bound is `{generator_bound}`.  Producer indices are not theorem premises:
all subgroup order, minimality, supremum, and normal-closure claims below
are rechecked by `native_decide` on the executable Cayley group.
-/

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section
open scoped Classical

namespace SymmetricSubgroupAsymptotics.{module}

open {class_module}
open {structural_module}
open Non2UnipotentPrefixFiniteMenu
namespace RowNormals := {normal_module}

local instance selectedSourceGroup : Group Source := group

private def rowState (i : Fin {normal_count}) : Subgroup Source :=
  Subgroup.closure (Set.range (RowNormals.stateGenerators i))

private theorem row_state_injective : Function.Injective rowState := by
  native_decide

noncomputable def rowRegistry : FiniteNormalStateRegistry Source :=
  FiniteNormalStateRegistry.ofWordRegistry
    conjugacyChunk.toCardinalCover
    {class_module}.ambient RowNormals.stateGenerators
    RowNormals.normalRegistry row_state_injective

noncomputable def originalRegistry : FiniteNormalStateRegistry Original :=
  rowRegistry.mapEquiv originalEquiv

private abbrev RR := rowRegistry
private abbrev R := originalRegistry

private theorem rowRegistry_state (i : Fin {normal_count}) :
    RR.state i = rowState i := rfl

private def RowIsMinimalStateAbove
    (base j : Fin {normal_count}) : Prop :=
  rowState base < rowState j ∧
    ∀ k : Fin {normal_count}, rowState base < rowState k →
      rowState k ≤ rowState j → rowState k = rowState j

private theorem rowRegistry_minimal_iff
    (base j : Fin {normal_count}) :
    RR.IsMinimalStateAbove base j ↔
      RowIsMinimalStateAbove base j := by
  rfl

private def carrierState (i : Fin {normal_count}) : Fin {normal_count} :=
  {fin_cases_chain(carrier_values)}

{chr(10).join(generator_definitions)}
private def rowGenerator : Fin {normal_count} → Fin {generator_bound} → Source :=
  {fin_cases_chain(generator_names)}

private theorem row_carrier_eq_checked : ∀ i : Fin {normal_count},
    rowState (carrierState i) = rowState i ⊔
      ⨆ j : {{j : Fin {normal_count} // RowIsMinimalStateAbove i j}},
        rowState j.1 := by
  native_decide

private theorem row_generated_checked : ∀ i : Fin {normal_count},
    Subgroup.normalClosure (Set.range (rowGenerator i)) ⊔ rowState i =
      rowState (carrierState i) := by
  native_decide

noncomputable def rowStateData (i : Fin {normal_count}) :
    FiniteRelativeSocleGeneratorData Source (RR.state i)
      {generator_bound} :=
  RR.relativeSocleGeneratorDataOfStates i (carrierState i)
    {generator_bound}
    {{j : Fin {normal_count} // RowIsMinimalStateAbove i j}}
    Subtype.val
    (fun j ↦ (rowRegistry_minimal_iff i j).2 j.property)
    (fun j hj ↦
      ⟨⟨j, (rowRegistry_minimal_iff i j).1 hj⟩, rfl⟩)
    (by simpa only [rowRegistry_state] using row_carrier_eq_checked i)
    (rowGenerator i)
    (by simpa only [rowRegistry_state] using row_generated_checked i)

noncomputable def stateData (i : Fin {normal_count}) :
    FiniteRelativeSocleGeneratorData Original (R.state i)
      {generator_bound} :=
  (rowStateData i).mapEquiv originalEquiv

noncomputable def family :
    R.QuotientSocleGeneratorFamily {generator_bound} where
  data := stateData

/-- Every literal quotient of this selected action has its socle normally
generated by the displayed uniformly padded tuple. -/
noncomputable def quotientSocleGenerator
    (N : {{N : Subgroup Original // N.Normal}}) :
    SocleNormalGeneratorBound (Original ⨸ N.1) {generator_bound} :=
  family.dispatch N

/-- The published Žmud theorem turns the checked socle tuple into a
jointly faithful tuple of irreducible complex representations. -/
noncomputable def quotientCharacterCertificate
    (hZmud : ZmudFaithfulCharacterTupleInput)
    (N : {{N : Subgroup Original // N.Normal}}) :
    CharacterQuotientCertificate (Original ⨸ N.1) :=
  hZmud.generalCertificate (quotientSocleGenerator N)

/-- The same tuple is a zero-relative binary-kernel anchor when its pure
ordinary profile is available in a pair-row menu. -/
noncomputable def quotientBinaryKernelAnchor
    (hZmud : ZmudFaithfulCharacterTupleInput)
    (N : {{N : Subgroup Original // N.Normal}}) :
    PrimitiveAffineImprimitiveBlockTransfer.DegreeTwoPairBinaryKernelAnchor
      (Original ⨸ N.1)
      (PrimitiveAffineImprimitiveBlockTransfer.degreeTwoPairGeneralProfile
        {generator_bound}) :=
  PrimitiveAffineImprimitiveBlockTransfer.DegreeTwoPairBinaryKernelAnchor.
    ofSocleGeneratorBound hZmud (quotientSocleGenerator N)

end SymmetricSubgroupAsymptotics.{module}

end
"""
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, action="append", type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--module", required=True)
    parser.add_argument("--class-module", required=True)
    parser.add_argument("--normal-module", required=True)
    parser.add_argument("--structural-module", required=True)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    for name in (args.module, args.class_module, args.normal_module,
                 args.structural_module):
        require(MODULE_RE.fullmatch(name) is not None,
                "invalid Lean module name")
    require(len(set(args.input)) == len(args.input),
            "duplicate normal input")
    chunks = [read_chunk(path) for path in args.input]
    prepared = validate_and_prepare(chunks, read_pinned_data())
    plans = validated_plans(prepared)
    payload = emit_module(
        args.module, args.class_module, args.normal_module,
        args.structural_module, prepared, plans,
        [path.name for path in args.input]).encode()
    require(len(payload) <= OUTPUT_LIMIT, "Lean output byte ceiling reached")
    write_atomic(args.output, payload, args.force)
    print(f"{args.output}: {len(payload)} bytes; "
          f"action {prepared['action_id']}; generator bound "
          f"{max(1, max(len(p['generator_class_indices']) for p in plans))}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, Refused, PlanRefused) as error:
        raise SystemExit(f"refused: {error}")
