#!/usr/bin/env python3
"""Emit one bounded normal-state or quotient-socle certificate from an existing top.

Reuses the selected encoded top and normal-word registry. It does not build
another ambient action table. The selected top ceiling is 288 elements,
32 normal states and 16 generators. Run through bounded_python_stage.py.
"""
from pathlib import Path
import argparse
import itertools
import re


def arr(xs):
    return '#[' + ', '.join(map(str, xs)) + ']'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--lean-dir', type=Path, required=True)
    ap.add_argument('--top-module', required=True)
    ap.add_argument('--normal-module', required=True)
    ap.add_argument('--module', required=True)
    ap.add_argument('--states-module')
    ap.add_argument('--chunk', choices=['normal-states', 'socle-table'], required=True)
    ap.add_argument('--output', type=Path, required=True)
    a = ap.parse_args()
    assert all(x.isidentifier() for x in [a.top_module, a.normal_module, a.module])
    assert not a.output.exists(), 'refusing to overwrite an existing certificate'
    inputs = [a.lean_dir / (x + '.lean') for x in [a.top_module, a.normal_module]]
    assert all(p.stat().st_size <= 8 * 1024 * 1024 for p in inputs)
    top, normal = (p.read_text() for p in inputs)
    m = re.search(r'private def codes \(i : Fin (\d+)\) : Fin \(8\^8\) :=\n([^\n]+)', top)
    assert m, 'expected an existing encoded eight-point top'
    order = int(m[1]); assert 1 < order <= 288
    codes = list(map(int, re.findall(r'\b(?:then|else) (\d+)', m[2])))
    assert len(codes) == len(set(codes)) == order
    perms = [tuple(c // 8**i % 8 for i in range(8)) for c in codes]
    assert perms[0] == tuple(range(8))
    lookup = {v: i for i, v in enumerate(perms)}
    def mul(i, j):
        return lookup[tuple(perms[i][perms[j][k]] for k in range(8))]
    m = re.search(r'def stateGenerators : Fin (\d+) → Fin (\d+) → Source', normal)
    count, width = map(int, m.groups())
    assert count <= 32 and 0 < width <= 16
    tables, masks = [], []
    for i in range(count):
        body = normal.split(f'private def state{i}Generators', 1)[1].split('\n\n', 1)[0]
        gens = list(map(int, re.findall(r'⟨(\d+)⟩', body)))
        assert len(gens) == width and all(g < order for g in gens)
        rows, parents, letters, indices = [0], [0], [0], {0: 0}
        for x in rows:
            for j, g in enumerate(gens):
                y = mul(x, g)
                if y not in indices:
                    indices[y] = len(rows); rows.append(y)
                    parents.append(indices[x]); letters.append(j)
        nxt = [[indices[mul(x, g)] for g in gens] for x in rows]
        tables.append((rows, parents, letters, nxt))
        masks.append(sum(1 << j for j in rows))
    assert len(set(masks)) == count, 'normal-state list contains duplicates'
    le = [[masks[i] & masks[j] == masks[i] for j in range(count)] for i in range(count)]
    header = f'''import SymmetricSubgroupAsymptotics.BinaryPairFiniteRows
import SymmetricSubgroupAsymptotics.{a.normal_module}

/-! Selected normal states, reusing the existing encoded top and word registry.
Generated by emit_lean_normal_state_socles.py; all finite facts use the kernel. -/
set_option autoImplicit false
set_option backward.isDefEq.respectTransparency false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section
open scoped Classical
namespace SymmetricSubgroupAsymptotics.{a.module}
abbrev Source := {a.top_module}.Source
local instance sourceGroup : Group Source := {a.top_module}.group

def state (i : Fin {count}) : Subgroup Source :=
  Subgroup.closure (Set.range ({a.normal_module}.stateGenerators i))
'''
    parts = [header]
    if a.chunk == 'normal-states':
        for i, (rows, parents, letters, nxt) in enumerate(tables):
            n = len(rows)
            parts.append(f'''namespace S{i}
private def rows (j : Fin {n}) : Fin {order} :=
  ({arr(rows)} : Array (Fin {order}))[j.val]!
private def next (j : Fin {n}) (k : Fin {width}) : Fin {n} :=
  (({arr(map(arr,nxt))} : Array (Array (Fin {n})))[j.val]!)[k.val]!
private def parent (j : Fin {n}) : Fin {n} :=
  ({arr(parents)} : Array (Fin {n}))[j.val]!
private def letter (j : Fin {n}) : Fin {width} :=
  ({arr(letters)} : Array (Fin {width}))[j.val]!
def certificate : EncodedCayleyCertificate
    (binaryNormalRowEncoding ({a.normal_module}.stateGenerators {i})) {n} where
  rows := rows
  identity := 0
  identity_eq := by decide +kernel
  next := next
  next_eq := by decide +kernel
  rank j := j.val
  parent j _ := parent j
  letter j _ := letter j
  parent_lt := by decide +kernel
  parent_next := by decide +kernel
end S{i}
''')
        parts.append(f'''def normalMask (i : Fin {count}) (x : Fin {order}) : Bool :=
  (({arr(masks)} : Array ℕ)[i.val]!).testBit x.val
''')
        for i in range(count):
            parts.append(f'''private theorem mask_checked{i} (x : Fin {order}) :
    normalMask {i} x = true ↔ ∃ j, S{i}.certificate.rows j = x := by
  decide +kernel +revert
''')
        parts.append(f'''theorem normalMask_mem (i : Fin {count}) (x : Source) :
    normalMask i x.index = true ↔ x ∈ state i := by
  fin_cases i
''' + ''.join(f'  · exact (mask_checked{i} x.index).trans (binaryNormalRow_mem_iff S{i}.certificate x).symm\n' for i in range(count)))
        parts.append(f'''abbrev MaskLE (i j : Fin {count}) : Prop :=
  ∀ x : Fin {order}, normalMask i x = true → normalMask j x = true

theorem state_le_iff_maskLE (i j : Fin {count}) : state i ≤ state j ↔ MaskLE i j := by
  constructor
  · intro h x hx
    exact (normalMask_mem j (⟨x⟩ : Source)).mpr
      (h ((normalMask_mem i (⟨x⟩ : Source)).mp hx))
  · intro h x hx
    exact (normalMask_mem j x).mp (h x.index ((normalMask_mem i x).mpr hx))

theorem state_injective : Function.Injective state := by
  have h : ∀ i j : Fin {count}, MaskLE i j → MaskLE j i → i = j := by
    decide +kernel
  intro i j hij
  exact h i j ((state_le_iff_maskLE i j).mp hij.le)
    ((state_le_iff_maskLE j i).mp hij.ge)
''')
    else:
        assert a.states_module and a.states_module.isidentifier()
        ns = a.states_module
        reps_body = top.split('private def representativeRows ', 1)[1].split('\n\n', 1)[0]
        reps = list(map(int, re.findall(r'\b(?:then|else) (\d+)', reps_body)))
        assert reps and reps[0] == 0
        carriers, tuples, gin = [], [], []
        for i in range(count):
            atoms = [j for j in range(count) if i != j and le[i][j] and not any(
                k != i and k != j and le[i][k] and le[k][j] for k in range(count))]
            uppers = [k for k in range(count) if le[i][k] and all(le[j][k] for j in atoms)]
            c = min(uppers, key=lambda k: masks[k].bit_count())
            assert all(le[c][k] for k in uppers)
            carriers.append(c)
            candidates = [x for x in reps if masks[c] >> x & 1]
            def generates(pair):
                return all(not le[i][k] or not all(masks[k] >> x & 1 for x in pair) or le[c][k]
                           for k in range(count))
            pair = next((p for p in itertools.combinations_with_replacement(candidates, 2) if generates(p)), None)
            assert pair is not None, f'no two-representative socle witness above state {i}'
            tuples.append(pair)
            gin.append([all(masks[k] >> x & 1 for x in pair) for k in range(count)])
        def bmatrix(matrix):
            return arr(arr('true' if b else 'false' for b in row) for row in matrix)
        parts = [f'''import SymmetricSubgroupAsymptotics.FiniteNormalStateSocleTable
import SymmetricSubgroupAsymptotics.{ns}

/-! One selected table instantiates the uniform quotient-socle theorem. -/
set_option autoImplicit false
set_option backward.isDefEq.respectTransparency false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
noncomputable section
open scoped Classical
namespace SymmetricSubgroupAsymptotics.{a.module}
open Non2UnipotentPrefixFiniteMenu
abbrev Source := {a.top_module}.Source
local instance sourceGroup : Group Source := {a.top_module}.group
abbrev Top := Subgroup.closure (Set.range {a.top_module}.generators)

noncomputable def normalRegistry : FiniteNormalStateRegistry Source :=
  FiniteNormalStateRegistry.ofWordRegistry
    {a.normal_module}.topConjugacy.toCardinalCover
    {a.normal_module}.topAmbient {a.normal_module}.stateGenerators
    {a.normal_module}.data {ns}.state_injective

private def leTest (i j : Fin {count}) : Bool :=
  (({bmatrix(le)} : Array (Array Bool))[i.val]!)[j.val]!

private theorem leTest_checked : ∀ i j : Fin {count},
    leTest i j = true ↔ {ns}.MaskLE i j := by decide +kernel

private def carrier (i : Fin {count}) : Fin {count} :=
  ({arr(carriers)} : Array (Fin {count}))[i.val]!

private def generator (i : Fin {count}) (j : Fin 2) : Source :=
  ⟨(({arr(map(arr,tuples))} : Array (Array (Fin {order})))[i.val]!)[j.val]!⟩

private def generatorIn (i k : Fin {count}) : Bool :=
  (({bmatrix(gin)} : Array (Array Bool))[i.val]!)[k.val]!

private theorem generatorIn_checked : ∀ i k : Fin {count},
    generatorIn i k = true ↔ ∀ j : Fin 2,
      {ns}.normalMask k (generator i j).index = true := by decide +kernel

private theorem carrier_upper_checked : ∀ i : Fin {count},
    leTest i (carrier i) = true ∧ ∀ j : Fin {count},
      finiteNormalTableMinimal leTest i j → leTest j (carrier i) = true := by decide +kernel

private theorem carrier_least_checked : ∀ i k : Fin {count}, leTest i k = true →
    (∀ j : Fin {count}, finiteNormalTableMinimal leTest i j → leTest j k = true) →
      leTest (carrier i) k = true := by decide +kernel

private theorem generator_mem_checked : ∀ i : Fin {count},
    generatorIn i (carrier i) = true := by decide +kernel

private theorem generator_generates_checked : ∀ i k : Fin {count},
    leTest i k = true → generatorIn i k = true → leTest (carrier i) k = true := by decide +kernel

noncomputable def socleTable : FiniteNormalStateSocleTable normalRegistry 2 where
  leTest := leTest
  le_iff i j := ({ns}.state_le_iff_maskLE i j).trans (leTest_checked i j).symm
  carrier := carrier
  carrier_upper := carrier_upper_checked
  carrier_least := carrier_least_checked
  generator := generator
  generatorIn := generatorIn
  generatorIn_iff i k := (generatorIn_checked i k).trans
    (forall_congr' (fun j ↦ {ns}.normalMask_mem k (generator i j)))
  generator_mem := generator_mem_checked
  generator_generates := generator_generates_checked

/-- All literal normal axes are discharged by the same checked table. -/
theorem topSocle (N : {{N : Subgroup Top // N.Normal}}) :
    SocleNormalGeneratorBound (Top ⧸ N.1) 2 :=
  FiniteNormalStateRegistry.QuotientSocleGeneratorFamily.dispatch
    (normalRegistry.mapEquiv {a.top_module}.originalEquiv)
    (socleTable.mapFamily {a.top_module}.originalEquiv) N
''']
        print('Carriers:', carriers, 'generator pairs:', tuples)
    parts.append(f'end SymmetricSubgroupAsymptotics.{a.module}\nend\n')
    result = '\n'.join(parts)
    assert len(result.encode()) <= 1024 * 1024
    a.output.write_text(result)
    print(a.output.name, 'states', count, 'orders', [len(x[0]) for x in tables], 'bytes', len(result.encode()))

if __name__ == '__main__':
    main()
